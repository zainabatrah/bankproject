const cloneAlerts = () =>
  demoAlerts.map((alert) => ({
    ...alert,
    transaction: {
      ...alert.transaction,
      senderAccount: alert.transaction.senderAccount
        ? {
            ...alert.transaction.senderAccount,
            user: { ...alert.transaction.senderAccount.user },
          }
        : null,
      receiverAccount: alert.transaction.receiverAccount
        ? {
            ...alert.transaction.receiverAccount,
            user: { ...alert.transaction.receiverAccount.user },
          }
        : null,
    },
  }))

export function getDemoDataForRole(role: UserRole): DemoBankData {
  const isCustomer = role === 'CUSTOMER' || role === 'BANK_EMPLOYEE'
  const canReviewAlerts =
    role === 'FRAUD_ANALYST' || role === 'SECURITY_ANALYST' || role === 'ADMIN'
  const canReviewAuditLogs = role === 'SECURITY_ANALYST' || role === 'ADMIN'

  return {
    accounts: isCustomer ? demoAccounts.map((account) => ({ ...account })) : [],
    transactions: isCustomer
      ? demoTransactions.map((transaction) => ({ ...transaction }))
      : [],
    beneficiaries: isCustomer
      ? demoBeneficiaries.map((beneficiary) => ({ ...beneficiary }))
      : [],
    devices: isCustomer ? demoDevices.map((device) => ({ ...device })) : [],
    alerts: canReviewAlerts ? cloneAlerts() : [],
    users: role === 'ADMIN'
      ? demoUsers.map((user) => ({
          ...user,
          _count: user._count ? { ...user._count } : undefined,
        }))
      : [],
    auditLogs: canReviewAuditLogs
      ? demoAuditLogs.map((log) => ({
          ...log,
          user: log.user ? { ...log.user } : null,
        }))
      : [],
  }
}
